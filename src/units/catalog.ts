function dataCategories(): Category[] {
  const entries: Unit[] = [
    unit('bit', 'bit', 'Bit', 'bit', '1', 'other', [], IEC),
    unit('byte', 'B', 'Byte', 'byte', '8', 'other', ['Byte'], IEC),
  ];
  const decimal = ['k', 'M', 'G', 'T', 'P'];
  const binary = ['Ki', 'Mi', 'Gi', 'Ti', 'Pi'];
  const de = ['Kilo', 'Mega', 'Giga', 'Tera', 'Peta'];
  const binaryNames = ['Kibi', 'Mebi', 'Gibi', 'Tebi', 'Pebi'];
  for (let i = 0; i < decimal.length; i++) {
    const p = decimal[i] ?? '';
    const b = binary[i] ?? '';
    const name = de[i] ?? '';
    entries.push(
      unit(
        `${p}B`,
        `${p}B`,
        name + 'byte',
        name.toLowerCase() + 'byte',
        new UDecimal(1000)
          .pow(i + 1)
          .mul(8)
          .toFixed(),
        'other',
        [],
        IEC,
      ),
    );
    entries.push(
      unit(
        `${b}B`,
        `${b}B`,
        (binaryNames[i] ?? '') + 'byte',
        (binaryNames[i] ?? '').toLowerCase() + 'byte',
        new UDecimal(1024)
          .pow(i + 1)
          .mul(8)
          .toFixed(),
        'other',
        [],
        IEC,
      ),
    );
    entries.push(
      unit(
        `${p}bit`,
        `${p}bit`,
        name + 'bit',
        name.toLowerCase() + 'bit',
        `1e${3 * (i + 1)}`,
        'other',
        [],
        IEC,
      ),
    );
  }
  const rates = entries.map((u) => ({
    ...u,
    id: `${u.id}-s`,
    symbol: `${u.symbol}/s`,
    names: { de: `${u.names.de} pro Sekunde`, en: `${u.names.en} per second` },
    aliases: u.id === 'bit' ? ['bps'] : u.id === 'byte' ? ['Bps'] : [],
    source: IEC + ' Per SI second.',
  }));
  return [
    category('data', 'Datenmenge', 'Data size', 'bit', entries),
    category('data-rate', 'Datenrate', 'Data rate', 'bit-s', rates),
  ];
}
