import type Decimal from 'decimal.js';
import { UDecimal, pi } from './decimal.ts';
import type { Category, Conversion, Unit, UnitSystem } from './types.ts';

const SI =
  'BIPM SI Brochure, 9th edition: SI units, prefixes and accepted non-SI units.';
const NIST =
  'NIST SP 811 Appendix B.8/B.9 and footnotes; exact customary definitions, not rounded table factors.';
const IAU =
  'IAU 2012 B2 and 2015 B2: au = 149597870700 m; pc = 648000 au / pi.';
const IEC =
  'IEC 80000-13: byte = 8 bits; decimal SI prefixes and binary prefixes (powers of 1024).';

function linear(factor: string): Conversion {
  const [numerator = '1', divisor] = factor.split('/');
  return { kind: 'linear', factor: numerator, ...(divisor ? { divisor } : {}) };
}
function unit(
  id: string,
  symbol: string,
  de: string,
  en: string,
  factor: string | Conversion,
  system: UnitSystem = 'si',
  aliases: readonly string[] = [],
  source = SI,
  note?: string,
  exact = true,
): Unit {
  return {
    id,
    symbol,
    names: { de, en },
    aliases,
    system,
    conversion: typeof factor === 'string' ? linear(factor) : factor,
    source,
    exact,
    ...(note ? { note } : {}),
  };
}
function category(
  id: string,
  de: string,
  en: string,
  baseUnitId: string,
  units: readonly Unit[],
  extra: Partial<Category> = {},
): Category {
  return { id, names: { de, en }, baseUnitId, units, ...extra };
}
const scale = (factor: () => Decimal): Conversion => ({
  kind: 'function',
  toBase: (v) => v.mul(factor()),
  fromBase: (v) => v.div(factor()),
});
const reciprocal = (numerator: string, denominator = '1'): Conversion => ({
  kind: 'function',
  toBase: (v) => new UDecimal(numerator).div(denominator).div(v),
  fromBase: (v) => new UDecimal(numerator).div(denominator).div(v),
});

/** Prefix entries are declarative data; factors never pass through binary floats. */
const prefixes = [
  ['n', 'Nano', 'nano', '-9'],
  ['µ', 'Mikro', 'micro', '-6'],
  ['m', 'Milli', 'milli', '-3'],
  ['', '', '', '0'],
  ['k', 'Kilo', 'kilo', '3'],
  ['M', 'Mega', 'mega', '6'],
] as const;
function prefixed(id: string, symbol: string, de: string, en: string): Unit[] {
  return prefixes.map(([p, d, e, exponent]) =>
    unit(
      p ? `${id}-${p === 'µ' ? 'micro' : p}` : id,
      p + symbol,
      d + de.toLowerCase(),
      e + en.toLowerCase(),
      `1e${exponent}`,
      'si',
      p === 'µ' ? ['u' + symbol] : [],
    ),
  );
}

