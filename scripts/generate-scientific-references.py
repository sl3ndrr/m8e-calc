"""Independent 80-digit Decimal reference formulas (no engine imports)."""
from decimal import Decimal as D, getcontext
from math import factorial, comb, perm
from pathlib import Path
import json
getcontext().prec = 80
PI = D('3.141592653589793238462643383279502884197169399375105820974944592307816406286208998628')
cases = []
def add(src, value, tolerance='1e-44', **extra):
    cases.append(dict(src=src, expected=str(value), tolerance=tolerance, **extra))
for n in range(21): add(f'factorial({n})', factorial(n))
for n in range(1,21):
    add(f'nCr({n}, {n//2})', comb(n,n//2))
    add(f'nPr({n}, {min(n,3)})', perm(n,min(n,3)))
for n in range(1,26):
    # Gamma(n+1/2) = (2n)! sqrt(pi)/(4^n n!)
    v=D(factorial(2*n))*PI.sqrt()/(D(4)**n*D(factorial(n)))
    add(f'gamma({D(n)+D("0.5")})', v, '5e-16')
add('gamma(0.5)', PI.sqrt(), '5e-16')
add('gamma(-0.5)', -2*PI.sqrt(), '5e-16')
add('gamma(1/3)', '2.678938534707747633655692940974677644128689377957301100950428327', '5e-16')
add('gamma(2/3)', '1.354117939426400416945288028154513785519327266056793698394022467', '5e-16')
add('gamma(0.25)', '3.625609908221908311930685155867672002995167682880065467433', '5e-16')
for n in range(0,21): add(f'integral(x^{n},x,0,1)' if n else 'integral(1,x,0,1)', D(1)/D(n+1), '1e-11')
for n in range(1,16): add(f'deriv(x^{n},x,2)', n*2**(n-1), '1e-11')
for x in ['-3','-1','-0.1','0','0.1','1','3']:
    a=D(x); ep=a.exp(); em=(-a).exp()
    add(f'sinh({x})',(ep-em)/2)
    add(f'cosh({x})',(ep+em)/2)
    add(f'tanh({x})',(ep-em)/(ep+em))
for n in range(1,16):
    args=','.join(str(i) for i in range(1,n+1))
    add(f'total({args})', n*(n+1)//2)
    add(f'mean({args})', D(n+1)/2)
    add(f'median({args})', D(n+1)/2)
    add(f'count({args})', n)
    if n>1:
        add(f'variance({args})',D(n)*(n+1)/12)
        add(f'stdev({args})',(D(n)*(n+1)/12).sqrt())
    add(f'stdevp({args})',(D(n*n-1)/12).sqrt())
for src,re,im in [
 ('exp(i*pi)+1','0','0'),('e^(i*pi)+1','0','0'),('i^2','-1','0'),
 ('sqrt(-1)','0','1'),('ln(-1)','0',str(PI)),
 ('(1+i)*(1-i)','2','0'),('1/i','0','-1'),('conj(3+4i)','3','-4'),
 ('sin(i)','0',str((D(1).exp()-D(-1).exp())/2)),
 ('cos(i)',str((D(1).exp()+D(-1).exp())/2),'0'),
 ('exp(ln(2+3i))','2','3'),('sqrt(3+4i)','2','1')]:
 cases.append(dict(src=src,re=re,im=im,tolerance='1e-43',complex='on'))
for src,v in [('integral(sin(x),x,0,pi)',2),('integral(exp(x),x,0,1)',D(1).exp()-1),('integral(1/(1+x^2),x,0,1)',PI/4),('integral(sqrt(x),x,0,1)',D(2)/3),('sum(k^2,k,1,100)',338350),('prod(k,k,1,10)',3628800),('deg2rad(180)',PI),('rad2deg(pi)',180),('frac(-3.75)','-0.75'),('round(123.45,-1)',120)]: add(src,v,'1e-11' if src.startswith('integral') else '1e-44')
p=Path('src/engine/scientificReferenceCases.ts')
p.write_text('// Generated by scripts/generate-scientific-references.py; independent 80-digit formulas.\nexport const scientificReferenceCases = '+json.dumps(cases,ensure_ascii=False,indent=2)+' as const;\n')
print(len(cases),'scientific reference cases')
