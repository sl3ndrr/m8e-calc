import { writeFileSync } from 'node:fs';
import { format } from 'prettier';
import { typeScale } from '../src/styles/typeScale.ts';
import { shapes } from '../src/styles/shapes.ts';
import { motionProperties } from '../src/styles/motion.ts';
import { buildScheme } from '../src/styles/buildScheme.ts';
const palette = buildScheme('#6750a4');
const root = Object.entries({ ...motionProperties, ...palette }).map(
  ([name, value]) => `  ${name}: ${value};`,
);
const utilities = [];
for (const [name, value] of Object.entries(shapes)) {
  root.push(`  --md-sys-shape-${name}: ${value}px;`);
  utilities.push(
    `.shape-${name} { border-radius: var(--md-sys-shape-${name}); }`,
  );
}
for (const [
  name,
  size,
  line,
  weight,
  emphasized,
  tracking,
  emphasizedTracking,
] of typeScale) {
  for (const emphasis of [false, true]) {
    const key = `${name}${emphasis ? '-emphasized' : ''}`;
    const prefix = `--md-sys-typescale-${key}`;
    const axes = `"wght" ${emphasis ? emphasized : weight}, "wdth" ${emphasis && /^(display|headline)/.test(name) ? 95 : 100}, "opsz" ${size}`;
    const tokens = {
      font: '"Roboto Flex", sans-serif',
      size: `${size / 16}rem`,
      'line-height': `${line / 16}rem`,
      weight: emphasis ? emphasized : weight,
      tracking: `${emphasis ? emphasizedTracking : tracking}px`,
      axes,
    };
    for (const [property, value] of Object.entries(tokens))
      root.push(`  ${prefix}-${property}: ${value};`);
    utilities.push(
      `.type-${key} { font-family: var(${prefix}-font); font-size: var(${prefix}-size); line-height: var(${prefix}-line-height); font-weight: var(${prefix}-weight); letter-spacing: var(${prefix}-tracking); font-variation-settings: var(${prefix}-axes); }`,
    );
  }
}
const registrations = Object.entries(palette).map(
  ([name, value]) =>
    `@property ${name} { syntax: '<color>'; inherits: true; initial-value: ${value}; }`,
);
const transition = Object.keys(palette)
  .map(
    (name) =>
      `${name} var(--md-sys-motion-effects-default-duration) var(--md-sys-motion-effects-default-easing)`,
  )
  .join(',\n  ');
writeFileSync(
  new URL('../src/styles/tokens.css', import.meta.url),
  await format(
    `/* Generated by npm run tokens. Edit typeScale.ts, shapes.ts or motion.ts. */\n${registrations.join('\n')}\n:root {\n${root.join('\n')}\n}\n:root[data-theme-ready='true'][data-motion='full']:not([data-theme-changing]) {\n  transition: ${transition};\n}\n${utilities.join('\n')}\n@supports (corner-shape: squircle) { .shape-squircle { corner-shape: squircle; } }\n`,
    { parser: 'css', singleQuote: true },
  ),
);
